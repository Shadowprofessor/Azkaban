import { launch, startSite } from "./harness.mjs";
const site = await startSite();
const { ctx, sw, extId } = await launch();
const page = await ctx.newPage();
await page.goto(site.url);
const tabId = await sw.evaluate(async () => (await chrome.tabs.query({ url: "http://127.0.0.1/*" }))[0]?.id);
const popup = await ctx.newPage();
await popup.goto(`chrome-extension://${extId}/popup.html?tab=${tabId}`);
await popup.click("[data-testid=patronus-toggle]");
await popup.waitForTimeout(800);
const rules = await sw.evaluate(async () => (await chrome.declarativeNetRequest.getDynamicRules()).map((r) => [r.id, r.condition.requestDomains.length, r.condition.domainType]));
console.log("rules:", JSON.stringify(rules));
await page.bringToFront();
await page.evaluate(() => window.fireTrackers());
await page.waitForTimeout(2000);
let t = await sw.evaluate(async (id) => (await chrome.storage.session.get(`tab:${id}`))[`tab:${id}`], tabId);
console.log("blocked with Patronus on:", t?.blocked, "| page title still:", await page.title());
// Escape hatch
await popup.reload(); await popup.waitForTimeout(500);
await popup.click("[data-testid=pause]");
await popup.waitForTimeout(800);
const r2 = await sw.evaluate(async () => (await chrome.declarativeNetRequest.getDynamicRules())[0]?.condition.excludedInitiatorDomains);
console.log("paused for:", JSON.stringify(r2));
await page.reload(); await page.evaluate(() => window.fireTrackers()); await page.waitForTimeout(2000);
t = await sw.evaluate(async (id) => (await chrome.storage.session.get(`tab:${id}`))[`tab:${id}`], tabId);
console.log("blocked after pause:", t?.blocked ?? 0, "| trackers seen:", t?.trackers);
await popup.reload(); await popup.waitForTimeout(500);
await popup.screenshot({ path: "e2e/popup7.png" });
await ctx.close(); site.close();
